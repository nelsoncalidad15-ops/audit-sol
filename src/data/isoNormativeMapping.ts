/**
 * Función que enriquece un AuditItem con la clasificación normativa ISO 9001
 * sin modificar ninguno de sus datos originales.
 */
export function enrichAuditItem(item: any): any {
  const meta = ISO_NORMATIVE_MAPPING[item.id] || ISO_NORMATIVE_MAPPING[item.code];
  if (!meta) {
    return {
      ...item,
      originType: item.originType || 'pending',
      isoClause: item.isoClause || '8. Operación',
      whatToVerify: item.whatToVerify || item.requirement,
      whatToShow: item.whatToShow || 'Documentación y registros respaldatorios de la operación.',
      howToCheck: item.howToCheck || item.howToAudit || 'Consultar con el responsable del área.',
      internalNotes: item.internalNotes || '',
    };
  }

  return {
    ...item,
    originType: item.originType || meta.originType,
    isoClause: item.isoClause || meta.isoClause,
    whatToVerify: item.whatToVerify || meta.whatToVerify,
    whatToShow: item.whatToShow || meta.whatToShow,
    howToCheck: item.howToCheck || meta.howToCheck,
    internalNotes: item.internalNotes || meta.internalNotes,
  };
}
